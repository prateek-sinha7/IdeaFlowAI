#!/usr/bin/env python3
"""Export a validated workflow manifest into the shapes the platform accepts.

  --yaml OUT            workflow.yaml for an engineer-shipped workflow
                        (<workflows>/<id>/workflow.yaml). Uses PyYAML when installed
                        and verifies the round trip; otherwise writes JSON, which is
                        valid YAML.
  --save-payload OUT    body for POST /api/user-workflows (save as a Composer workflow).
  --run-payload OUT     body for POST /api/runs (Run once, inline manifest, user trust).
                        Needs --message.

Validate first: python validate_manifest.py FILE --trust <target>
Stdlib only (PyYAML optional).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def compiled_root_ids(manifest: dict) -> list[str]:
    ids = []
    for step in manifest.get("steps") or []:
        agent = step.get("agent")
        iid = step.get("instance_id")
        ids.append(f"{agent}:{iid}" if agent == "custom-agent" and iid else agent)
    return [i for i in ids if i]


def to_yaml(manifest: dict) -> tuple[str, str]:
    try:
        import yaml  # type: ignore
    except ImportError:
        return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", "PyYAML missing: wrote JSON (valid YAML)"

    class Dumper(yaml.SafeDumper):
        pass

    def represent_str(dumper, data):
        style = "|" if "\n" in data else None
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)

    Dumper.add_representer(str, represent_str)
    text = yaml.dump(manifest, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=100, default_flow_style=False)
    if yaml.safe_load(text) != manifest:
        return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", "YAML round trip differed: wrote JSON (valid YAML)"
    return text, "YAML (round trip verified)"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("manifest", type=Path)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--yaml", type=Path, metavar="OUT")
    group.add_argument("--save-payload", type=Path, metavar="OUT")
    group.add_argument("--run-payload", type=Path, metavar="OUT")
    parser.add_argument("--message", help="the brief for --run-payload")
    parser.add_argument("--name", help="saved workflow name (default: manifest name or id)")
    args = parser.parse_args(argv)

    try:
        manifest = json.loads(args.manifest.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as exc:
        print(f"error: cannot read {args.manifest}: {exc}", file=sys.stderr)
        return 2
    if not isinstance(manifest, dict) or not manifest.get("steps"):
        print("error: not a workflow manifest with steps", file=sys.stderr)
        return 2

    if args.yaml:
        text, note = to_yaml(manifest)
        header = f"# {manifest.get('id')}: generated by the velocity-workflow-creator skill. Validate before shipping.\n"
        args.yaml.parent.mkdir(parents=True, exist_ok=True)
        args.yaml.write_text(header + text, encoding="utf-8")
        print(f"wrote {args.yaml}: {note}")
        return 0

    if args.save_payload:
        payload = {
            "name": (args.name or manifest.get("name") or manifest.get("id"))[:120],
            "description": (manifest.get("description") or "")[:2000] or None,
            "base_pipeline_type": "custom",
            "agent_ids": compiled_root_ids(manifest),
            "manifest": manifest,
        }
        out = args.save_payload
        note = ("POST /api/user-workflows (bearer token). Runs at 'db' trust only for callers entitled to the "
                "custom pipeline; otherwise at 'user'.")
    else:
        if not args.message:
            print("error: --run-payload needs --message", file=sys.stderr)
            return 2
        payload = {"message": args.message, "pipeline_type": "custom", "manifest": manifest}
        out = args.run_payload
        note = ("POST /api/runs (bearer token). Inline manifests compile at 'user' trust. Add staged_upload_ids, "
                "template_id or images when the workflow needs them; do not send deliverable/planner/clarify/"
                "capabilities unless you mean to override the manifest's values.")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {out}: {note}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
