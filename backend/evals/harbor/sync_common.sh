#!/usr/bin/env bash
# Assemble every Harbor task directory from its two sources, before each run.
#
# A task here is a point on a grid: STAGE x SCENARIO.
#
#   common/<stage>/   what it means to grade `specify` or `plan` — the gating
#                     rules, the instruction wording, the coverage regexes.
#                     Identical for every scenario.
#   scenarios/<name>/ which product is being asked for — the brief, the domain
#                     vocabulary the contract gates on, the reference answer.
#                     Identical for every stage.
#
# Neither dimension may hold the other's content. That is the rule this layout
# exists to enforce: before it, a second scenario meant a second copy of the
# stage verifier, and a second stage a second copy of the pages list.
#
# Task dirs are named <scenario>-<stage> and hold ONE hand-written file,
# task.toml. Everything else below is generated and gitignored, so editing
# common/ or scenarios/ takes effect on the next run with nothing to remember.
#
# Why generate rather than import: Harbor uploads a task's own tests/,
# environment/ and solution/ into the container and nothing else. There is no
# shared volume or import path to point at, so shared files must be physically
# present in each task.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MINIMAL="$(cd "$HERE/../minimal" && pwd)"

count=0
for task in "$HERE"/*-specify/ "$HERE"/*-plan/; do
  [[ -d "$task" ]] || continue
  name="$(basename "$task")"
  stage="${name##*-}"                 # trailing segment: specify | plan
  scenario="${name%-"$stage"}"        # everything before it
  src="$HERE/scenarios/$scenario"

  if [[ ! -d "$src" ]]; then
    echo "    $name: no scenarios/$scenario — skipped" >&2
    continue
  fi

  mkdir -p "$task/tests" "$task/environment" "$task/solution"
  cp "$HERE/common/verifier.py"            "$task/tests/verifier.py"
  cp "$HERE/common/test.sh"                "$task/tests/test.sh"
  cp "$HERE/common/$stage/test_outputs.py" "$task/tests/test_outputs.py"
  cp "$src/contract.json"                  "$task/tests/contract.common.json"
  cp "$HERE/common/Dockerfile"             "$task/environment/Dockerfile"
  cp "$HERE/common/task.gitignore"         "$task/.gitignore"
  chmod +x "$task/tests/test.sh"

  python3 - "$src" "$task" "$stage" "$MINIMAL" <<'PY'
import json, pathlib, sys

src, task, minimal = (pathlib.Path(p) for p in (sys.argv[1], sys.argv[2], sys.argv[4]))
stage = sys.argv[3]
harbor = src.parents[1]
contract = json.loads((src / "contract.json").read_text(encoding="utf-8"))

# ── instruction = stage template (+ the brief, for specify) ──────────────
# The brief is READ FROM THE EVAL DATASET rather than copied into the scenario,
# so Harbor and evals/minimal can never grade two different wordings of the
# same request. `row_id` in the scenario contract is the join key.
text = (harbor / "common" / stage / "instruction.md").read_text(encoding="utf-8")
if stage == "specify":
    row_id = contract["row_id"]
    for dataset in sorted((minimal / "datasets").glob("*.json")):
        rows = json.loads(dataset.read_text(encoding="utf-8"))
        rows = rows if isinstance(rows, list) else rows.get("rows", [])
        hit = next((r for r in rows if r.get("id") == row_id), None)
        if hit:
            text += hit["prompt"].strip() + "\n"
            break
    else:
        raise SystemExit(f"no dataset row {row_id!r} under {minimal / 'datasets'}")
(task / "instruction.md").write_text(text, encoding="utf-8")

# ── oracle ───────────────────────────────────────────────────────────────
# Harbor uploads the whole solution/ dir to /solution, so solve.sh only has to
# copy the reference artifact into place. Keeping that artifact as a plain .md
# (rather than a heredoc inside the script) makes it diffable, readable by the
# host-side judges, and free of shell-quoting hazards.
deliverable = {"specify": "spec.md", "plan": "tasks.md"}[stage]
(task / "solution" / deliverable).write_text(
    (src / "solution" / deliverable).read_text(encoding="utf-8"), encoding="utf-8")
solve = task / "solution" / "solve.sh"
solve.write_text(
    "#!/bin/bash\n"
    "# Generated by sync_common.sh — edit scenarios/*/solution/ instead.\n"
    f"cp /solution/{deliverable} /app/{deliverable}\n",
    encoding="utf-8")
solve.chmod(0o755)
PY
  count=$((count + 1))
done
echo "    assembled $count task(s) from common/ x scenarios/" >&2
